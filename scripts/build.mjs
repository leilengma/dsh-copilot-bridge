/**
 * Build the two release artifacts from TypeScript sources.
 *
 * - `lib/index.js`: the Host plugin, an ES module loaded by the Harness Loader.
 * - `lib/client.js`: the Web client, a CommonJS body wrapped in the Harness
 *   `window.__ModuleLoader__.load()` envelope, whose `require` resolves the
 *   shared React and Harness client packages.
 */
import { build } from 'esbuild'
import { readFile, readdir, writeFile } from 'node:fs/promises'

const pkg = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'))
const define = { __PLUGIN_VERSION__: JSON.stringify(pkg.version) }

const host = await build({
  entryPoints: ['src/host/index.ts'],
  metafile: true,
  outfile: 'lib/index.js',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  // Bundle only reachable SDK code, not pi-ai's full install-time dependency tree.
  // Harness modules keep host identity; undici stays external for proxy support.
  external: ['@deepseek-ai/*', 'undici'],
  banner: { js: "import { createRequire as __bridgeCreateRequire } from 'node:module'; const require = __bridgeCreateRequire(import.meta.url);" },
  define,
  logLevel: 'warning',
})

await build({
  entryPoints: ['src/client/index.tsx'],
  outfile: 'lib/client.js',
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: 'es2022',
  jsx: 'automatic',
  loader: { '.svg': 'dataurl' },
  external: ['react', 'react/jsx-runtime', '@deepseek-ai/*'],
  define,
  banner: {
    js: [
      'window.__ModuleLoader__.load({',
      `  id: ${JSON.stringify(pkg.name)},`,
      '  factory: (require) => {',
      '    var module = { exports: {} };',
      '    var exports = module.exports;',
      '    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });',
    ].join('\n'),
  },
  footer: { js: '    return module.exports;\n  }\n});' },
  logLevel: 'warning',
})

// Retain the full license/notice texts for every package reachable in the host
// bundle. Two npm archives omit their license; use reviewed upstream snapshots,
// pinned by package version so dependency upgrades cannot silently reuse them.
const licenseSnapshots = {
  '@earendil-works/pi-ai@1.3.0': 'pi-ai.txt',
  'standardwebhooks@1.3.0': 'standardwebhooks.txt',
}
const packageDirs = [...new Set(Object.keys(host.metafile.inputs)
  .map(input => input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)/)?.[1])
  .filter(Boolean))].sort()
const notices = ['Bundled third-party software\nGenerated by scripts/build.mjs; do not edit.\nThese sources are bundled/transformed by esbuild; upstream license terms follow.']
for (const dir of packageDirs) {
  const dependency = JSON.parse(await readFile(`${dir}/package.json`, 'utf8'))
  const id = `${dependency.name}@${dependency.version}`
  const files = (await readdir(dir, { withFileTypes: true }))
    .filter(entry => entry.isFile() && /^(licen[cs]e|notice|copying)(\.|$)/i.test(entry.name))
    .map(entry => entry.name).sort()
  const texts = await Promise.all(files.map(file => readFile(`${dir}/${file}`, 'utf8')))
  if (texts.length === 0) {
    const snapshot = licenseSnapshots[id]
    if (!snapshot) throw new Error(`Missing bundled license for ${id}; review upstream before packaging`)
    texts.push(await readFile(new URL(`licenses/${snapshot}`, import.meta.url), 'utf8'))
  }
  notices.push(`${id}\nDeclared package license: ${dependency.license}\n\n${texts.join('\n\n').trimEnd()}`)
}
await writeFile('THIRD_PARTY_NOTICES.txt', `${notices.join('\n\n----------------------------------------\n\n')}\n`)

console.log(`built lib/index.js and lib/client.js (${pkg.name} v${pkg.version})`)
